/* ------------------------------ COMPOSER ------------------------------ */
/* A motif is a list of {d: scaleDegree offset, t: 8th-note position, l: length}.
   Sections re-use and transform the motif so the music has memory & shape.   */
function makeMotif(rng, len, dense) {
  const m = []; let pos = 0, d = rng.pick([0, 2, 4, 4, 2, 7]);
  const rhy = dense ? [1, 1, 2, 1, 2, 1, 1, 3] : [2, 2, 3, 1, 4, 2, 3, 2];
  while (pos < len) {
    const l = rng.pick(rhy);
    if (rng.chance(dense ? .1 : .22)) { pos += l; continue; }         // rests give phrasing
    m.push({ d, t: pos, l: Math.min(l, len - pos) });
    const step = rng.wpick([-4, -2, -1, 1, 2, 3, 4, 0], [1, 3, 5, 5, 4, 2, 1, 1]);
    d = clamp(d + step, -3, 11);
    pos += l;
  }
  return m;
}
function transformMotif(m, rng, variant) {
  if (variant === 0) return m;
  return m.map(n => {
    const o = { d: n.d, t: n.t, l: n.l };
    if (variant === 1) o.d += 2;                       // transpose up a third
    else if (variant === 2) o.d = 7 - o.d;             // inversion around 5th
    else if (variant === 3) { o.d -= 2; o.l = Math.max(1, o.l - 1); }
    return o;
  });
}
function newSection(score) {
  const rng = new RNG((A.seed * 2654435761 + A.sect * 40503 + score.bpm) | 0);
  A.motif = makeMotif(rng, 16, score.bpm > 118);
  A.motifRng = rng;
}

/* ------------------------------ SCHEDULER ------------------------------ */
const SPB = () => 60 / A.bpm;      // seconds per beat (quarter)
const S8 = () => 30 / A.bpm;       // seconds per 8th

function musicSet(stateName, immediate) {
  if (!A.ok) return;
  if (A.state === stateName && !A.pending) return;
  if (!A.scores[stateName]) return;
  A.pending = stateName;
  if (immediate || !A.score) applyPending();
}
function applyPending() {
  if (!A.pending) return;
  const s = A.scores[A.pending];
  A.state = A.pending; A.pending = '';
  A.score = s; A.bpm = s.bpm; A.bar = 0; A.beat = 0; A.sect++;
  newSection(s);
  if (A.musicBus) {
    const t = A.ctx.currentTime;
    A.musicBus.gain.cancelScheduledValues(t);
    A.musicBus.gain.setValueAtTime(Math.max(.0001, A.musicBus.gain.value), t);
    A.musicBus.gain.linearRampToValueAtTime(A.muted ? 0 : A.volMusic, t + 1.6);
  }
}
