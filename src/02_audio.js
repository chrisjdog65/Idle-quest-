/* ------------------------------ VOICES ------------------------------ */
function env(g, t, a, d, s, r, dur, peak) {
  const p = peak == null ? 1 : peak;
  g.gain.cancelScheduledValues(t);
  g.gain.setValueAtTime(0.0001, t);
  g.gain.exponentialRampToValueAtTime(Math.max(0.0002, p), t + a);
  g.gain.exponentialRampToValueAtTime(Math.max(0.0002, p * s), t + a + d);
  g.gain.setValueAtTime(Math.max(0.0002, p * s), t + Math.max(a + d, dur));
  g.gain.exponentialRampToValueAtTime(0.0001, t + Math.max(a + d, dur) + r);
}
