/** midi -> hz */
const hz = m => 440 * Math.pow(2, (m - 69) / 12);
/** scale degree (can exceed octave, can be negative) -> midi offset */
function degToSemi(mode, d) {
  const sc = MODES[mode], n = sc.length;
  const oct = Math.floor(d / n), i = ((d % n) + n) % n;
  return sc[i] + oct * 12;
}
/** build a triad/seventh from a scale degree */
function chordNotes(mode, root, deg, seventh, oct) {
  const o = (oct || 0) * 12;
  const a = [degToSemi(mode, deg), degToSemi(mode, deg + 2), degToSemi(mode, deg + 4)];
  if (seventh) a.push(degToSemi(mode, deg + 6));
  return a.map(s => root + s + o);
}

