/* ------------------------------ INIT ------------------------------ */
function audioInit(seed) {
  if (A.ctx) return true;
  try {
    const AC = window.AudioContext || window.webkitAudioContext;
    if (!AC) return false;
    A.ctx = new AC({ latencyHint: 'interactive' });
  } catch (e) { return false; }
  const c = A.ctx;
  A.seed = seed || 1;

  A.comp = c.createDynamicsCompressor();
  A.comp.threshold.value = -14; A.comp.knee.value = 26; A.comp.ratio.value = 3.2;
  A.comp.attack.value = 0.006; A.comp.release.value = 0.26;

  A.master = c.createGain(); A.master.gain.value = 0.9;
  A.master.connect(A.comp); A.comp.connect(c.destination);

  A.musicBus = c.createGain(); A.musicBus.gain.value = A.volMusic;
  A.sfxBus = c.createGain(); A.sfxBus.gain.value = A.volSfx;
  A.musicBus.connect(A.master); A.sfxBus.connect(A.master);

  // ---- reverb (generated impulse response: exponential-decay noise) ----
  const rev = c.createConvolver();
  const len = Math.floor(c.sampleRate * 2.9);
  const ir = c.createBuffer(2, len, c.sampleRate);
  const rr = new RNG(A.seed ^ 0x5eed);
  for (let ch = 0; ch < 2; ch++) {
    const d = ir.getChannelData(ch);
    for (let i = 0; i < len; i++) {
      const t = i / len;
      // early reflections + smooth tail
      const env = Math.pow(1 - t, 2.6) * (1 - Math.exp(-i / (c.sampleRate * 0.012)));
      d[i] = (rr.f() * 2 - 1) * env;
    }
  }
  rev.buffer = ir;
  A.revIn = c.createGain(); A.revIn.gain.value = 1;
  const revOut = c.createGain(); revOut.gain.value = 0.5;
  const revLP = c.createBiquadFilter(); revLP.type = 'lowpass'; revLP.frequency.value = 4200;
  A.revIn.connect(rev); rev.connect(revLP); revLP.connect(revOut); revOut.connect(A.master);

  // ---- shared noise buffer ----
  const nlen = Math.floor(c.sampleRate * 2);
  A.noiseBuf = c.createBuffer(1, nlen, c.sampleRate);
  const nd = A.noiseBuf.getChannelData(0);
  for (let i = 0; i < nlen; i++) nd[i] = rr.f() * 2 - 1;

  A.scores = buildScores(new RNG(A.seed).ri(52, 59)); // root between E3 and G3
  A.ok = true;
  return true;
}
